package io.skis.processor;

import java.util.Locale;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.ArrayType;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;

final class SourceText {

  static final int GENERATED_ABI = 9;
  static final String GENERATED_COMMENT = "// Generated by SKIS. Do not edit.\n";
  static final String GENERATED_ANNOTATION =
      "@org.jspecify.annotations.NullMarked\n"
          + "@javax.annotation.processing.Generated(value = \"io.skis.processor.SkisEntityProcessor\", comments = \"ABI "
          + GENERATED_ABI
          + "\")\n";
  private static final char[] HEX_DIGITS = "0123456789abcdef".toCharArray();
  private static final java.util.Set<String> RESERVED_META_FIELDS =
      java.util.Set.of("TABLE", "ENTITY", "VERSION", "PRIMARY_KEY", "GENERATED_ABI");

  private SourceText() {}

  /** Renders supported value types without type arguments or type-use annotations. */
  static String erasedTypeName(TypeMirror type) {
    if (type instanceof ArrayType array) {
      return erasedTypeName(array.getComponentType()) + "[]";
    }
    if (type.getKind().isPrimitive()) {
      return type.getKind().name().toLowerCase(Locale.ROOT);
    }
    if (type instanceof DeclaredType declared) {
      return ((TypeElement) declared.asElement()).getQualifiedName().toString();
    }
    throw new IllegalArgumentException("unsupported source value type " + type);
  }

  /** Places a type-use annotation on the value, including qualified and array types. */
  static String nullableType(String typeName) {
    int depth = 0;
    int qualifier = -1;
    for (int index = 0; index < typeName.length(); index++) {
      char character = typeName.charAt(index);
      if (character == '<') {
        depth++;
      } else if (character == '>') {
        depth--;
      } else if (depth == 0 && character == '.') {
        qualifier = index;
      } else if (depth == 0 && character == '[') {
        return typeName.substring(0, index)
            + " @org.jspecify.annotations.Nullable "
            + typeName.substring(index);
      }
    }
    return typeName.substring(0, qualifier + 1)
        + "@org.jspecify.annotations.Nullable "
        + typeName.substring(qualifier + 1);
  }

  static String string(String value) {
    StringBuilder escaped = new StringBuilder(value.length() + 2);
    escaped.append('"');
    for (int index = 0; index < value.length(); index++) {
      char character = value.charAt(index);
      switch (character) {
        case '\\' -> escaped.append("\\\\");
        case '"' -> escaped.append("\\\"");
        case '\b' -> escaped.append("\\b");
        case '\n' -> escaped.append("\\n");
        case '\f' -> escaped.append("\\f");
        case '\r' -> escaped.append("\\r");
        case '\t' -> escaped.append("\\t");
        default -> {
          if (Character.isISOControl(character)) {
            appendOctalEscape(escaped, character);
          } else if (Character.isSurrogate(character)
              || character == '\u2028'
              || character == '\u2029') {
            appendUnicodeEscape(escaped, character);
          } else {
            escaped.append(character);
          }
        }
      }
    }
    return escaped.append('"').toString();
  }

  static String constantName(String value) {
    StringBuilder result = new StringBuilder(value.length() + 8);
    for (int index = 0; index < value.length(); index++) {
      char current = value.charAt(index);
      boolean uppercase = Character.isUpperCase(current);
      if (uppercase
          && index > 0
          && (Character.isLowerCase(value.charAt(index - 1))
              || Character.isDigit(value.charAt(index - 1))
              || (index + 1 < value.length() && Character.isLowerCase(value.charAt(index + 1))))) {
        result.append('_');
      }
      result.append(Character.toLowerCase(current));
    }
    return result.toString().toUpperCase(Locale.ROOT);
  }

  static String propertyFieldName(String propertyName) {
    String candidate = constantName(propertyName);
    return RESERVED_META_FIELDS.contains(candidate) ? candidate + "_PROPERTY" : candidate;
  }

  static String tableSingletonName(String entityName) {
    return Character.toLowerCase(entityName.charAt(0)) + entityName.substring(1) + "Table";
  }

  private static void appendOctalEscape(StringBuilder target, char character) {
    target.append('\\');
    target.append((char) ('0' + (character >>> 6 & 0x7)));
    target.append((char) ('0' + (character >>> 3 & 0x7)));
    target.append((char) ('0' + (character & 0x7)));
  }

  private static void appendUnicodeEscape(StringBuilder target, char character) {
    target.append("\\u");
    target.append(HEX_DIGITS[character >>> 12 & 0xF]);
    target.append(HEX_DIGITS[character >>> 8 & 0xF]);
    target.append(HEX_DIGITS[character >>> 4 & 0xF]);
    target.append(HEX_DIGITS[character & 0xF]);
  }
}
